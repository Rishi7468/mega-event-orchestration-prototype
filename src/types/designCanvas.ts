import type { LatLng } from "@/data/geography";
import type { OperationalZoneDefinition, PlacedAsset } from "@/store/eventAuthoringStore";

export type DesignObjectType = "zone" | "cctv" | "route" | "landmark";

export type DesignHandleType =
  | "move"
  | "nw"
  | "n"
  | "ne"
  | "e"
  | "se"
  | "s"
  | "sw"
  | "w"
  | "radius"
  | "heading"
  | "range"
  | "vertex";

export type SVGPoint = {
  x: number;
  y: number;
};

export type DesignZone = {
  id: string;
  name: string;
  code: string;
  type: OperationalZoneDefinition["type"];
  shapeType: "rectangle" | "circle" | "polygon";
  // Pixels in SVG container space
  centerPx: SVGPoint;
  widthPx: number;
  heightPx: number;
  radiusPx: number;
  verticesPx: SVGPoint[];
  // Geo reference
  centerGeo: LatLng;
  boundaryGeo: LatLng[];
  // Attributes
  capacity: number;
  riskLevel: OperationalZoneDefinition["riskLevel"];
  operationalState?: OperationalZoneDefinition["operationalState"];
  customColor?: string;
  colorMode?: "operational" | "custom";
  isLocked?: boolean;
  category?: OperationalZoneDefinition["category"];
  isAutoGenerated?: boolean;
};

export type DesignCCTV = {
  id: string;
  name: string;
  posPx: SVGPoint;
  posGeo: LatLng;
  zoneId: string;
  heading: number; // degrees 0-360
  fov: number; // degrees 30-120
  rangePx: number; // pixels in SVG container space
  rangeMeters: number;
  coveragePercent: number;
  status: PlacedAsset["status"];
  isAutoGenerated?: boolean;
};

export type DesignSessionState = {
  isDesignModeActive: boolean;
  isMapLocked: boolean;
  selectedObjectId: string | null;
  selectedObjectType: "zone" | "cctv" | null;
  activeHandle: { objectId: string; handleType: DesignHandleType; vertexIndex?: number } | null;
  dragStartPt: SVGPoint | null;
  zones: DesignZone[];
  cctvs: DesignCCTV[];
  historyPast: { zones: DesignZone[]; cctvs: DesignCCTV[] }[];
  historyFuture: { zones: DesignZone[]; cctvs: DesignCCTV[] }[];
};
